#!/usr/bin/env node
// Generates the merchant map-pin sprites used by the natively-clustered
// merchant layer (#1073) — the same composite-pin approach btcmap.org
// uses (their `maplibreSprites.ts` composes a pin + glyph SVG and
// registers it as a MapLibre style image; we pre-generate at build time
// instead of rasterising at runtime, which RN can't do cheaply).
//
// One PNG per UNIQUE Lucide glyph × payment colour:
//   assets/map-pins/<colour>-<glyph>.png   (colour: ln | onchain)
// rendered at 3× (96 px for a 32 px chassis) so pins stay crisp on
// phone-class DPRs — mirroring btcmap.org's PIN_RENDER_SCALE = 3.
//
// Re-run after changing src/utils/btcMapIconNames.json (the shared
// btcmap-name → lucide-glyph mapping) or the chassis colours:
//   node scripts/generate-map-pin-sprites.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const mapping = JSON.parse(
  readFileSync(join(root, 'src/utils/btcMapIconNames.json'), 'utf8'),
);

// Chassis colours mirror LibreMiniMap.styles: brandPink for Lightning,
// Bitcoin-orange for on-chain-only (`pinOnchain`).
const COLOURS = { ln: '#EC008C', onchain: '#F7931A' };
// 32 px chassis (MapScreen's uniformMarkerSize) at 3× render scale.
const SIZE = 32;
const SCALE = 3;

const glyphs = [...new Set(Object.values(mapping))];
const outDir = join(root, 'assets/map-pins');
mkdirSync(outDir, { recursive: true });

for (const glyph of glyphs) {
  const svgPath = join(root, 'node_modules/lucide-static/icons', `${glyph}.svg`);
  // Lucide SVGs are 24×24 stroke outlines; recolour to white and embed
  // centred at 60% of the chassis, matching the RN pin proportions.
  const inner = readFileSync(svgPath, 'utf8')
    .replace(/stroke="currentColor"/g, 'stroke="#FFFFFF"')
    .replace(/<svg /, '<svg x="6.4" y="6.4" width="19.2" height="19.2" ');
  for (const [colourName, fill] of Object.entries(COLOURS)) {
    const composite = `<svg xmlns="http://www.w3.org/2000/svg" width="${SIZE}" height="${SIZE}" viewBox="0 0 ${SIZE} ${SIZE}">
  <circle cx="16" cy="16" r="15" fill="${fill}" stroke="#FFFFFF" stroke-width="2"/>
  ${inner}
</svg>`;
    const png = join(outDir, `${colourName}-${glyph}.png`);
    await sharp(Buffer.from(composite), { density: 72 * SCALE })
      .resize(SIZE * SCALE, SIZE * SCALE)
      .png()
      .toFile(png);
  }
}

// Emit the require() manifest the Images component consumes — Metro
// needs static require paths, so the manifest is generated, not dynamic.
const lines = [];
lines.push('// AUTO-GENERATED by scripts/generate-map-pin-sprites.mjs — do not edit.');
lines.push('// Sprite name → bundled asset for the merchant symbol layer (#1073).');
lines.push('/* eslint-disable @typescript-eslint/no-require-imports */');
lines.push('export const MAP_PIN_SPRITES: Record<string, number> = {');
for (const glyph of glyphs) {
  for (const colourName of Object.keys(COLOURS)) {
    lines.push(`  '${colourName}-${glyph}': require('../../assets/map-pins/${colourName}-${glyph}.png'),`);
  }
}
lines.push('};');
writeFileSync(join(root, 'src/utils/mapPinSprites.ts'), lines.join('\n') + '\n');

console.log(`generated ${glyphs.length * 2} sprites for ${glyphs.length} glyphs`);
